/**
 * The evidence index's data layer.
 *
 * Artifacts are discovered with `import.meta.glob(..., { eager: false })` so a new file
 * in `src/data/analysis/` appears without a code change, and so the index does not pull
 * the artifact payloads into the initial bundle — `cv_kfold.json` alone is 1.8 MB.
 *
 * Only the *facts* (schema, timestamp, row count) require reading a payload, and each
 * of those is fetched when the row is first rendered.
 */
import { ARTIFACT_DESCRIPTIONS } from './artifactDescriptions'
import { formatRowCount, formatTimestamp, readArtifactFacts, type ArtifactFacts } from './artifactFacts'

/** Every artifact on disk, keyed by basename. Metadata only until fetched. */
const ARTIFACT_MODULES = import.meta.glob<Record<string, unknown>>('../data/analysis/*.json')

export type EvidenceRow = {
  /** Basename without `.json`. */
  name: string
  /** `src/data/analysis/<name>.json` */
  path: string
  description: string
  /** A module imports this artifact and can use its values. */
  imported: boolean
  /** Some module names the file, even if it is not imported. */
  referenced: boolean
  /** Source files that import it, for the "seven of thirty-one" conversation. */
  importedBy: string[]
  /** Declared row count, once the payload has been read. */
  rowCount?: number
  /**
   * Set when this row's declared sample disagrees with the majority of rows: the row
   * count most other artifacts report. Carries that majority so the warning can name it.
   */
  conflictsWithRows?: number
  /**
   * Why the row count differs from the rest of the set, when that is legitimate.
   *
   * `lockbox_holdout` reports 87 because 87 is the panel the reserved set was drawn
   * from (17 of its cells withheld) — not because it is stale. Flagging it as stale would
   * be a false alarm on a correct number, which is how a reader learns to ignore flags.
   */
  rowCountIsSubset?: boolean
}

export type EvidenceIndex = {
  rows: EvidenceRow[]
  /** Artifacts whose JSON is imported by a module. */
  importedCount: number
  /** Artifacts named in source but not imported. */
  referencedOnlyCount: number
  /** Artifacts no module mentions at all. */
  untouchedCount: number
  total: number
}

/**
 * Consumption facts, generated by `scripts/generate_evidence_consumption.ts`.
 *
 * Kept as a generated module rather than a build-time `node:fs` scan because the
 * browser cannot read the source tree. The generator is checked by
 * `npm run check:evidence-index`, which re-derives the same answers from `src/` and
 * fails on a mismatch — so the data cannot drift from the code it describes.
 */
type ConsumptionFacts = {
  imported: readonly string[]
  referencedOnly: readonly string[]
}

/**
 * Lazily read the facts for one artifact.
 *
 * Never throws: an artifact that cannot be read is reported as having no facts, which
 * the renderer shows as em dashes. An index that fails to render because one JSON is
 * malformed would be worse than an index with one blank row.
 */
export async function loadArtifactFacts(name: string): Promise<ArtifactFacts> {
  const loader = ARTIFACT_MODULES[`../data/analysis/${name}.json`]
  if (!loader) return {}
  try {
    return readArtifactFacts(await loader())
  } catch {
    return {}
  }
}

export { formatRowCount, formatTimestamp }
export type { ArtifactFacts }

function artifactNameFromPath(filePath: string): string {
  const file = filePath.slice(filePath.lastIndexOf('/') + 1)
  return file.replace(/\.json$/, '')
}

/**
 * Build the index from the glob and the generated consumption facts.
 *
 * Ordering is by name so the list is stable across renders and diffable in review.
 */
/**
 * Majority row count, when the rows disagree.
 *
 * Several artifacts were generated on an earlier panel and were not regenerated after
 * the sample changed (167 -> 207 rows). Printing `146` beside `207` with no comment tells
 * a reader that 146 is the current sample. It is not: it is the sample as it stood on
 * 2026-11-09, and the artifact has not been rebuilt since.
 */
function findSampleConflicts(rows: { name: string; rowCount?: number }[]): Map<string, number> {
  const counted = rows.filter((r) => r.rowCount !== undefined)
  if (counted.length < 2) return new Map()

  const tally = new Map<number, number>()
  for (const row of counted) {
    tally.set(row.rowCount as number, (tally.get(row.rowCount as number) ?? 0) + 1)
  }

  let majority = 0
  let majorityCount = -1
  for (const [value, count] of tally) {
    if (count > majorityCount) {
      majority = value
      majorityCount = count
    }
  }

  const conflicts = new Map<string, number>()
  for (const row of counted) {
    // A unique tie cannot establish a majority, only an outlier worth flagging.
    if (row.rowCount !== majority) conflicts.set(row.name, majority)
  }
  return conflicts
}

/**
 * Attach the row counts the interface has loaded so far, and flag any row whose declared
 * sample disagrees with the majority.
 */
export function withFacts(index: EvidenceIndex, facts: Record<string, ArtifactFacts | undefined>): EvidenceIndex {
  const rows = index.rows.map((row) => ({ ...row, rowCount: facts[row.name]?.rowCount }))
  const conflicts = findSampleConflicts(rows)
  return {
    ...index,
    rows: rows.map((row) => {
      const loaded = facts[row.name]?.rowCount
      const differing = loaded === undefined ? undefined : conflicts.get(row.name)
      return {
        ...row,
        // Only meaningful once this row's own facts have loaded.
        conflictsWithRows: differing,
        rowCountIsSubset: differing !== undefined && SUBSET_ARTIFACTS.has(row.name),
      }
    }),
  }
}

/**
 * Artifacts whose declared count is a legitimate sub-sample of the panel, not a stale
 * one. Kept deliberately short and named: every entry here suppresses a warning, which is
 * exactly the kind of allowance that should be hard to add and easy to see.
 */
const SUBSET_ARTIFACTS: ReadonlySet<string> = new Set(['lockbox_holdout'])

export function buildEvidenceIndex(consumption: ConsumptionFacts): EvidenceIndex {
  const imported = new Set(consumption.imported)
  const referencedOnly = new Set(consumption.referencedOnly)

  const rows: EvidenceRow[] = Object.keys(ARTIFACT_MODULES)
    .map((filePath) => {
      const name = artifactNameFromPath(filePath)
      return {
        name,
        path: `src/data/analysis/${name}.json`,
        description: ARTIFACT_DESCRIPTIONS[name] ?? '',
        imported: imported.has(name),
        referenced: imported.has(name) || referencedOnly.has(name),
        importedBy: [],
      }
    })
    .sort((a, b) => a.name.localeCompare(b.name))

  const importedCount = rows.filter((r) => r.imported).length
  const referencedOnlyCount = rows.filter((r) => !r.imported && r.referenced).length

  return {
    rows,
    importedCount,
    referencedOnlyCount,
    untouchedCount: rows.length - importedCount - referencedOnlyCount,
    total: rows.length,
  }
}
